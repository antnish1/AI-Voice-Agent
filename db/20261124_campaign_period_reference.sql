begin;
create schema if not exists private_campaign_reference;
revoke all on schema private_campaign_reference from public, anon, authenticated;
create table if not exists private_campaign_reference.dealer_codes(
 dealership_id uuid primary key references public.dealerships(id),
 code text not null unique
);
create sequence if not exists private_campaign_reference.dealer_code_seq;
insert into private_campaign_reference.dealer_codes(dealership_id,code)
values ('98468a52-9b19-4647-9ae5-6ac984cc6b57','MG')
on conflict (dealership_id) do nothing;
create table if not exists private_campaign_reference.counters(
 dealership_id uuid not null references public.dealerships(id),
 period date not null,
 last_number bigint not null check(last_number>0),
 primary key(dealership_id,period)
);
alter table public.campaigns add column if not exists campaign_period date;
alter table public.campaigns add column if not exists campaign_reference text;
create unique index if not exists campaigns_reference_unique on public.campaigns(campaign_reference) where campaign_reference is not null;
create or replace function private_campaign_reference.assign_reference()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_code text; v_number bigint;
begin
 if tg_op='UPDATE' then
  if new.campaign_period is distinct from old.campaign_period or new.campaign_reference is distinct from old.campaign_reference or (old.campaign_reference is not null and new.name is distinct from old.name) then raise exception 'Campaign reference is immutable'; end if;
  return new;
 end if;
 if new.campaign_reference is not null then raise exception 'Campaign reference is generated by database'; end if;
 if new.campaign_period is null then return new; end if;
 if new.campaign_period < date '1900-01-01' or new.campaign_period > make_date(extract(year from timezone('Asia/Kolkata',now()))::int,12,1) or extract(day from new.campaign_period)<>1 then raise exception 'Invalid campaign period'; end if;
 insert into private_campaign_reference.dealer_codes(dealership_id,code)
 values(new.dealership_id,'DL'||nextval('private_campaign_reference.dealer_code_seq'::regclass)::text)
 on conflict(dealership_id) do nothing;
 select code into v_code from private_campaign_reference.dealer_codes where dealership_id=new.dealership_id;
 insert into private_campaign_reference.counters(dealership_id,period,last_number) values(new.dealership_id,new.campaign_period,1)
 on conflict(dealership_id,period) do update set last_number=private_campaign_reference.counters.last_number+1 returning last_number into v_number;
 new.campaign_reference := (array['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'])[extract(month from new.campaign_period)::int]||' '||extract(year from new.campaign_period)::int||' - '||v_code||'-'||lpad(v_number::text,greatest(4,length(v_number::text)),'0');
 new.name := new.campaign_reference;
 return new;
end $$;
revoke all on function private_campaign_reference.assign_reference() from public, anon, authenticated;
drop trigger if exists campaign_reference_assign on public.campaigns;
create trigger campaign_reference_assign before insert or update on public.campaigns for each row execute function private_campaign_reference.assign_reference();
create or replace function public.create_period_campaign_draft(p_dealership_id uuid,p_period date,p_configuration jsonb)
returns uuid language plpgsql security invoker set search_path='' as $$
declare v_id uuid;
begin
 if p_period is null then raise exception 'Campaign period required'; end if;
 if p_configuration is null or jsonb_typeof(p_configuration)<>'object' or octet_length(p_configuration::text)>16000 then raise exception 'Invalid draft configuration'; end if;
 insert into public.campaigns(dealership_id,name,status,created_by,campaign_period)
 values(p_dealership_id,'Campaign draft','DRAFT',(select auth.uid()),p_period) returning id into v_id;
 insert into public.campaign_draft_configs(campaign_id,dealership_id,configuration) values(v_id,p_dealership_id,p_configuration);
 return v_id;
end $$;
revoke all on function public.create_period_campaign_draft(uuid,date,jsonb) from public, anon;
grant execute on function public.create_period_campaign_draft(uuid,date,jsonb) to authenticated;
commit;
